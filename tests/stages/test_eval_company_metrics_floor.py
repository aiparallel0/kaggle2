"""PR FOCUS-COMPANY — pipeline ``company`` metric floor.

Pins the acceptance criteria from the problem statement: after wiring
the FOCUS-C company head into inference (mirror of FOCUS-A) and
composing :func:`models.postprocess_company.normalize_company_focus`
into the pipeline normaliser bundle, the canonical SROIE Task-3
(347-image) eval must reach:

* ``pipeline_f1_company > 0.90``
* ``pipeline_ned_company > 0.92``
* ``pipeline_em_company > 0.75``

with no regression on address / date / total (paired-bootstrap CI
overlap; here we just spot-check that each non-company F1 stays at or
above the pre-FOCUS-C baseline shipped in
``tests/fixtures/canonical_347_n1.json``).

Driven from a fixture rather than running eval (which needs a GPU and
the trained ``assigner.pt``) so the test is hermetic.  The fixture is
regenerated by the ops procedure documented in the PR description:

    bash scripts/vastai_update.sh eval && make paper

then ``cp runs/<latest>/metrics/extended_metrics.json
tests/fixtures/canonical_347_post_focus_c.json`` (filtered down to the
keys this test asserts on).
"""
from __future__ import annotations

import json
from pathlib import Path

_POST_FIXTURE = (
    Path(__file__).parents[1] / "fixtures" / "canonical_347_post_focus_c.json"
)
_BASELINE_FIXTURE = (
    Path(__file__).parents[1] / "fixtures" / "canonical_347_n1.json"
)


def _load(path: Path) -> dict[str, object]:
    with path.open(encoding="utf-8") as fh:
        return dict(json.load(fh))


def test_pipeline_f1_company_above_floor() -> None:
    """The FOCUS-C inference wiring lifts company F1 above 0.90."""
    metrics = _load(_POST_FIXTURE)
    f1 = float(metrics["pipeline_f1_company"])  # type: ignore[arg-type]
    assert f1 > 0.90, f"pipeline_f1_company={f1:.4f} ≤ 0.90 floor"


def test_pipeline_ned_company_above_floor() -> None:
    """Token-set NED rises with the symmetric ``normalize_company_focus``."""
    metrics = _load(_POST_FIXTURE)
    ned = float(metrics["pipeline_ned_company"])  # type: ignore[arg-type]
    assert ned > 0.92, f"pipeline_ned_company={ned:.4f} ≤ 0.92 floor"


def test_pipeline_em_company_above_floor() -> None:
    """Exact-match also lifts (suffix recovery + boilerplate prefix drop)."""
    metrics = _load(_POST_FIXTURE)
    em = float(metrics["pipeline_em_company"])  # type: ignore[arg-type]
    assert em > 0.75, f"pipeline_em_company={em:.4f} ≤ 0.75 floor"


def test_no_regression_on_other_fields() -> None:
    """No paired regression on address / date / total relative to the
    pre-FOCUS-C baseline.  Surfaces a violation as a per-field assertion
    so the failure message is debuggable.
    """
    post = _load(_POST_FIXTURE)
    base = _load(_BASELINE_FIXTURE)
    for field in ("address", "date", "total"):
        key = f"pipeline_f1_{field}"
        post_v = float(post[key])     # type: ignore[arg-type]
        base_v = float(base[key])     # type: ignore[arg-type]
        # Allow a 1 pt CI-overlap noise floor — the eval-arm bootstrap
        # 95 % CIs in the baseline fixture are ~3 pt wide, so a single
        # FOCUS-C wiring change will not move address/date/total by
        # more than the bootstrap noise floor (we only changed the
        # company head dispatch + the company normaliser).
        assert post_v >= base_v - 0.01, (
            f"regression on {field}: {post_v:.4f} < baseline {base_v:.4f}"
        )


def test_company_floor_fixture_keys_present() -> None:
    """Schema contract — the fixture must carry the three headline keys
    plus the per-field F1s the no-regression check reads.
    """
    metrics = _load(_POST_FIXTURE)
    required = {
        "pipeline_f1_company", "pipeline_ned_company", "pipeline_em_company",
        "pipeline_f1_address", "pipeline_f1_date", "pipeline_f1_total",
    }
    missing = required - metrics.keys()
    assert not missing, f"fixture missing keys: {sorted(missing)}"
